#!/usr/bin/env bash
# Provision a self-contained Android toolchain under ~/.local (no sudo).
#
#   tools/android-env.sh            # install missing pieces
#   tools/android-env.sh --check    # verify and print paths
#
# Installs JDK 17, Android cmdline-tools, platform 35, build-tools 35,
# platform-tools and Gradle 8.9. Writes android/local.properties and
# android/env.sh so the project builds with ./gradlew.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCAL="${HOME}/.local"
CACHE="${XDG_CACHE_HOME:-${HOME}/.cache}/comtudia-toolchain"

JDK_DIR="${LOCAL}/jdk17"
SDK_DIR="${LOCAL}/android-sdk"
GRADLE_DIR="${LOCAL}/gradle-8.9"

JDK_URL="https://api.adoptium.net/v3/binary/latest/17/ga/linux/x64/jdk/hotspot/normal/eclipse"
CMDLINE_URL="https://dl.google.com/android/repository/commandlinetools-linux-11076708_latest.zip"
GRADLE_URL="https://services.gradle.org/distributions/gradle-8.9-bin.zip"

PLATFORM="android-35"
BUILD_TOOLS="35.0.0"

log() { printf '==> %s\n' "$*"; }

have_jdk() { [[ -x "${JDK_DIR}/bin/javac" ]]; }
have_sdk() { [[ -x "${SDK_DIR}/cmdline-tools/latest/bin/sdkmanager" ]]; }

download() {
  local url="$1" dest="$2"
  mkdir -p "$CACHE"
  if [[ -s "$dest" ]]; then
    log "cached $(basename "$dest")"
    return
  fi
  log "downloading $(basename "$dest")"
  curl -fL --retry 3 --progress-bar "$url" -o "${dest}.part"
  mv "${dest}.part" "$dest"
}

check_only=0
[[ "${1:-}" == "--check" ]] && check_only=1

if (( check_only )); then
  have_jdk || { echo "missing JDK at ${JDK_DIR}" >&2; exit 1; }
  have_sdk || { echo "missing Android SDK at ${SDK_DIR}" >&2; exit 1; }
  [[ -x "${GRADLE_DIR}/bin/gradle" ]] || { echo "missing Gradle at ${GRADLE_DIR}" >&2; exit 1; }
  echo "JAVA_HOME=${JDK_DIR}"
  echo "ANDROID_HOME=${SDK_DIR}"
  echo "GRADLE=${GRADLE_DIR}/bin/gradle"
  exit 0
fi

mkdir -p "$LOCAL" "$CACHE"

if ! have_jdk; then
  archive="${CACHE}/temurin17.tar.gz"
  download "$JDK_URL" "$archive"
  log "extracting JDK"
  rm -rf "${LOCAL}/jdk17.tmp"
  mkdir -p "${LOCAL}/jdk17.tmp"
  tar -xzf "$archive" -C "${LOCAL}/jdk17.tmp" --strip-components=1
  rm -rf "$JDK_DIR"
  mv "${LOCAL}/jdk17.tmp" "$JDK_DIR"
fi
export JAVA_HOME="$JDK_DIR"
export PATH="${JAVA_HOME}/bin:${PATH}"

if ! have_sdk; then
  archive="${CACHE}/commandlinetools.zip"
  download "$CMDLINE_URL" "$archive"
  log "extracting cmdline-tools"
  rm -rf "${SDK_DIR}/cmdline-tools/latest"
  mkdir -p "${SDK_DIR}/cmdline-tools"
  unzip -q -o "$archive" -d "${SDK_DIR}/cmdline-tools"
  mv "${SDK_DIR}/cmdline-tools/cmdline-tools" "${SDK_DIR}/cmdline-tools/latest"
fi

export PATH="${SDK_DIR}/cmdline-tools/latest/bin:${SDK_DIR}/platform-tools:${PATH}"

log "accepting SDK licenses"
yes | sdkmanager --sdk_root="$SDK_DIR" --licenses >/dev/null 2>&1 || true

log "installing platform-tools, ${PLATFORM}, build-tools ${BUILD_TOOLS}"
sdkmanager --sdk_root="$SDK_DIR" --install \
  "platform-tools" "platforms;${PLATFORM}" "build-tools;${BUILD_TOOLS}" >/dev/null

if [[ ! -x "${GRADLE_DIR}/bin/gradle" ]]; then
  archive="${CACHE}/gradle-8.9-bin.zip"
  download "$GRADLE_URL" "$archive"
  log "extracting Gradle"
  rm -rf "${LOCAL}/gradle-8.9.tmp" "${GRADLE_DIR}"
  mkdir -p "${LOCAL}/gradle-8.9.tmp"
  unzip -q -o "$archive" -d "${LOCAL}/gradle-8.9.tmp"
  mv "${LOCAL}/gradle-8.9.tmp/gradle-8.9" "$GRADLE_DIR"
  rmdir "${LOCAL}/gradle-8.9.tmp"
fi

mkdir -p "${ROOT}/android"
printf 'sdk.dir=%s\n' "$SDK_DIR" > "${ROOT}/android/local.properties"

cat > "${ROOT}/android/env.sh" <<EOF
# Generated by tools/android-env.sh
export JAVA_HOME="${JDK_DIR}"
export ANDROID_HOME="${SDK_DIR}"
export ANDROID_SDK_ROOT="${SDK_DIR}"
export PATH="\${JAVA_HOME}/bin:\${ANDROID_HOME}/platform-tools:\${ANDROID_HOME}/emulator:\${ANDROID_HOME}/cmdline-tools/latest/bin:${GRADLE_DIR}/bin:\${PATH}"
EOF

log "done"
echo "  source android/env.sh"
echo "  cd android && ./gradlew :app:assembleDebug"
